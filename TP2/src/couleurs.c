#include <stdio.h>

struct Couleur {
    unsigned char r, g, b, a;
};

int main(void) {
    struct Couleur palette[10] = {
        {0xef, 0x78, 0x12, 0xff},
        {0x2c, 0xc8, 0x64, 0xff},
        {0x00, 0x00, 0x00, 0xff},
        {0xff, 0xff, 0xff, 0xff},
        {0xff, 0x00, 0x00, 0xff},
        {0x00, 0xff, 0x00, 0xff},
        {0x00, 0x00, 0xff, 0xff},
        {0x55, 0x55, 0x55, 0xff},
        {0xaa, 0xaa, 0xaa, 0xff},
        {0x12, 0x34, 0x56, 0x78}
    };

    for (int i = 0; i < 10; i++) {
        printf("Couleur %d :\nRouge : %d\nVert : %d\nBleu : %d\nAlpha : %d\n\n",
               i + 1, palette[i].r, palette[i].g, palette[i].b, palette[i].a);
    }

    return 0;
}